package net.ccbluex.liquidbounce.injection.mixins.minecraft.network;

import net.ccbluex.liquidbounce.interfaces.ClientboundSetEntityMotionPacketAccessor;
import net.minecraft.network.protocol.game.ClientboundSetEntityMotionPacket;
import net.minecraft.world.phys.Vec3;
import org.spongepowered.asm.mixin.Final;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Mutable;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.Unique;

@Mixin(ClientboundSetEntityMotionPacket.class)
public abstract class MixinClientboundSetEntityMotionPacket implements ClientboundSetEntityMotionPacketAccessor {

    @Mutable
    @Shadow
    @Final
    private Vec3 movement;

    @Unique
    @Override
    public void liquid_bounce$setMovement(Vec3 movement) {
        this.movement = movement;
    }

}
